#!/usr/bin/env python3
"""Turn analysis/reports/*.json into one readable index (analysis/reports/INDEX.md).

    python3 -I analysis/summarize.py --reports analysis/reports
"""
import argparse
import glob
import json
import os


def _cell(value):
    return "" if value is None else str(value)


def _convention(summary):
    s = summary.get("sfz_root_vs_pitch")
    if not s or s["compared"] < 20:
        return ""
    by = s.get("by_octave", {})
    best, n = max(by.items(), key=lambda kv: kv[1]) if by else ("?", 0)
    share = 100 * n / s["compared"]
    if share < 60:
        return f"mixed ({share:.0f}% agree)"
    if best == "0":
        return f"matches ({share:.0f}%)"
    sign = "above" if int(best) < 0 else "below"
    return f"root {abs(int(best))} oct {sign} sound ({share:.0f}%)"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--reports", default="analysis/reports")
    args = ap.parse_args()

    reports = []
    for path in sorted(glob.glob(os.path.join(args.reports, "*.json"))):
        with open(path, encoding="utf-8") as fh:
            reports.append(json.load(fh))

    lines = ["# Sample pack inventory", "",
             "Generated by `analysis/summarize.py` from `analysis/reports/*.json`.", "",
             "| pack | tier | files | minutes | pitch range | pitched | SFZ velocity layers | SFZ round robins | SFZ root vs sounding pitch |",
             "|---|---|---:|---:|---|---:|---:|---:|---|"]
    for rep in reports:
        s = rep["summary"]
        rng = s.get("pitch_range")
        lines.append("| " + " | ".join([
            rep["pack"], rep["tier"], _cell(s.get("files")), _cell(s.get("minutes")),
            f"{rng[0]}-{rng[1]}" if rng else "",
            f'{round(100 * s.get("pitched_ratio", 0))}%' if "pitched_ratio" in s else "",
            _cell(s.get("sfz_layers", {}).get("velocity_layers_max")),
            _cell(s.get("sfz_layers", {}).get("round_robins_max")),
            _convention(s)]) + " |")

    lines += ["", "## Notes", "",
              "- Pitch comes from audio analysis (YIN), not from file names. Many packs name files and map SFZ roots "
              "by written pitch, so the offset in the last column must be applied when building instruments.",
              "- Percussion packs (drums, hats) are mostly unpitched; ignore their pitch columns.",
              "- SFZ layers and round robins are the maximum on any one key, from the pack's root `.sfz` files "
              "(files that other `.sfz` files include are treated as fragments). Release-triggered samples and "
              "full-range add-ons are left out. Velocity ranges are counted as written, so packs that stack "
              "overlapping splits or gate layers behind a controller (drum kits with several mic layers, for "
              "example) read high. Packs without `.sfz` files show blanks.",
              "- `env` and `ends_cut` look at the first 4 seconds plus the last 100 ms of each file.", ""]
    out = os.path.join(args.reports, "INDEX.md")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {out} ({len(reports)} packs)")


if __name__ == "__main__":
    main()
